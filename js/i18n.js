const DICT = { es: ES, en: EN };
let lang = 'es';
try { lang = localStorage.getItem('surco:lang') || new URLSearchParams(location.search).get('lang') || 'es'; } catch { /* sin storage */ }

export function getLang() { return lang; }
export function setLang(l) { lang = l; try { localStorage.setItem('surco:lang', l); } catch { /* */ } }
export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT.es[key] ?? key;
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}
export function L(obj) { return obj?.[lang] ?? obj?.es ?? ''; }
export function fmt(n, d = 0) { return Number(n).toLocaleString(lang === 'es' ? 'es-BO' : 'en-US', { maximumFractionDigits: d, minimumFractionDigits: d }); }
